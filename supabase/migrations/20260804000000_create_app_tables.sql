/*
  # Create app tables used by the Hebasy frontend

  Tables created (idempotent):
    - `Blog`       - blog posts rendered by BlogList / BlogDetail
    - `gallery`    - portfolio videos rendered by Gallery
    - `comments`   - client testimonials rendered by Comments
    - `Reports`    - client portal data rendered by Login / PortalDashboard

  RLS:
    - Public SELECT for read-only content tables (Blog, gallery, comments, Reports)
    - Anon INSERT allowed for comments (public feedback)
    - Reports are readable by anon because the portal login uses the anon
      (publishable) client and authenticates via `client_code`.
*/

CREATE TABLE IF NOT EXISTS "Blog" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  content text NOT NULL,
  image_url text,
  slug text UNIQUE NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gallery (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  caption text,
  category text,
  video_url text NOT NULL,
  tiktok_url text,
  insta_url text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_name text NOT NULL,
  user_email text,
  company_name text,
  comment_text text NOT NULL,
  rating integer DEFAULT 5,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "Reports" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_code text UNIQUE NOT NULL,
  client_name text,
  package_name text,
  total_amount numeric,
  paid_amount numeric,
  remaining_amount numeric,
  total_videos_planned integer,
  videos_published integer,
  contract_duration text,
  contract_start text,
  contract_expiry text,
  next_content_topic text,
  editor_name text,
  host_name text,
  host_image_url text,
  host_instagram text,
  host_tiktok text,
  host_gender text,
  total_views numeric,
  total_engagement numeric,
  traffic_generated numeric,
  script_pdf_url text,
  content_calendar text,
  monthly_growth numeric,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE "Blog" ENABLE ROW LEVEL SECURITY;
ALTER TABLE gallery ENABLE ROW LEVEL SECURITY;
ALTER TABLE comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Reports" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public can read blog posts"
  ON "Blog" FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Public can read gallery"
  ON gallery FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Public can read comments"
  ON comments FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Anyone can submit a comment"
  ON comments FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

CREATE POLICY "Public can read reports"
  ON "Reports" FOR SELECT
  TO anon, authenticated
  USING (true);
